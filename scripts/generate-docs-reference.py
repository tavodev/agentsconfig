#!/usr/bin/env python3
"""Generate Sources/Services/DocsCatalogReference.swift from the official
settings references stored in scripts/docs-reference/*.json (Claude Code,
Codex, Gemini CLI, OpenCode).

Each JSON maps a config key to {"en", "es", "kind", "options", "custom",
"default", "scopes", "topic", "deprecated", "min", "max"} (see
scripts/refresh-docs-reference.py). The English text
comes from the official reference (Claude Code `settings-reference.md`,
Codex `config-reference.md`); the Spanish text is a reviewed translation.

Refresh workflow: update the JSON (add/remove keys, edit text), then run
    python3 scripts/generate-docs-reference.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "scripts" / "docs-reference"
OUT = ROOT / "Sources" / "Services" / "DocsCatalogReference.swift"


def lit(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def num(v):
    return "nil" if v is None else repr(float(v))


def table(name: str, source: str, url: str) -> str:
    entries = json.loads((DATA / f"{name}.json").read_text())
    rows = []
    for key in sorted(entries):
        e = entries[key]
        if not e.get("en") or not e.get("es"):
            raise SystemExit(f"{name}.json: {key} needs both en and es")
        options = ", ".join(lit(o) for o in e.get("options", []))
        scopes = ", ".join("." + s for s in e.get("scopes", []))
        default = "nil" if e.get("default") is None else lit(e["default"])
        rows.append(
            f"        {lit(key)}: .init(en: {lit(e['en'])}, es: {lit(e['es'])}, spec: .init(\n"
            f"            kind: .{e.get('kind', 'other')}, options: [{options}], allowsCustom: {str(e.get('custom', True)).lower()}, "
            f"defaultJSON: {default}, scopes: [{scopes}], topic: {lit(e.get('topic', ''))}, "
            f"deprecated: {str(e.get('deprecated', False)).lower()}, min: {num(e.get('min'))}, max: {num(e.get('max'))})),"
        )
    return (
        f"    /// {len(entries)} keys from {url}\n"
        f"    static let {source}: [String: ReferenceEntry] = [\n"
        + "\n".join(rows)
        + "\n    ]\n"
    )


OUT.write_text(
    "// Generated by scripts/generate-docs-reference.py — do not edit by hand.\n\n"
    "extension DocsCatalog {\n"
    + table("claude", "claudeReference", "https://code.claude.com/docs/en/settings-reference")
    + "\n"
    + table("codex", "codexReference", "https://developers.openai.com/codex/config-reference")
    + "\n"
    + table("gemini", "geminiReference", "https://github.com/google-gemini/gemini-cli/blob/main/schemas/settings.schema.json")
    + "\n"
    + table("opencode", "opencodeReference", "https://opencode.ai/config.json")
    + "}\n"
)
print(f"wrote {OUT.relative_to(ROOT)}")
